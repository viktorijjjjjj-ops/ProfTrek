def set_cell(cell, text):
    cell.text = ""
    paragraph = cell.paragraphs[0]
    paragraph.paragraph_format.space_after = Pt(3)
    run = paragraph.add_run(text)
    run.font.name = "Arial"
    run.font.size = Pt(9)


def append_answer(cell, text):
    paragraph = cell.add_paragraph()
    paragraph.paragraph_format.space_before = Pt(5)
    paragraph.paragraph_format.space_after = Pt(3)
    label = paragraph.add_run("ОТВЕТ УЧАСТНИКА\n")
    label.bold = True
    label.font.name = "Arial"
    label.font.size = Pt(9)
    label.font.color.rgb = BLUE
    answer = paragraph.add_run(text)
    answer.font.name = "Arial"
    answer.font.size = Pt(9)


def put(table, row, col, text, append=False):
    cell = table.rows[row].cells[col]
    if append:
        append_answer(cell, text)
    else:
        set_cell(cell, text)


